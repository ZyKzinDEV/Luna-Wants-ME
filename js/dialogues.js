// Função para carregar traduções adicionais
function loadAdditionalDialogues() {
    if (typeof Translations !== 'undefined' && Translations.dictionary) {
        for (let lang in DIALOGUE_TRANSLATIONS) {
            if (Translations.dictionary[lang]) {
                Object.assign(Translations.dictionary[lang], DIALOGUE_TRANSLATIONS[lang]);
            }
        }
        console.log('✅ Traduções de diálogos carregadas!');
    }
}

// Carregar quando a página estiver pronta
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', loadAdditionalDialogues);
} else {
    loadAdditionalDialogues();
}